'use client';

import { useEffect, useRef, useState } from 'react';

/**
 * True once the element has entered the viewport (by `threshold`). Stays true
 * so reveal animations run once and never pop back out while scrolling up.
 */
export function useInView<T extends HTMLElement>(threshold = 0.25, rootMargin = '0px 0px -8% 0px') {
  const ref = useRef<T>(null);
  const [inView, setInView] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (typeof IntersectionObserver === 'undefined') { setInView(true); return; }
    const io = new IntersectionObserver(
      (entries) => {
        for (const e of entries) {
          if (e.isIntersecting) { setInView(true); io.disconnect(); }
        }
      },
      { threshold, rootMargin }
    );
    io.observe(el);
    return () => io.disconnect();
  }, [threshold, rootMargin]);

  return { ref, inView };
}
